export const MESSAGES: Record<SupportedLocale, Record<MessageKey, string>> = { ko, en }

export const locale = ref<SupportedLocale>('ko')

export function setAppLocale(value: string): void {
  if (value === 'ko' || value === 'en') locale.value = value
}

/** 지금 언어의 문구. {name} 자리에 params 값을 넣는다. */
export function t(key: MessageKey, params: Record<string, string | number> = {}): string {
  return MESSAGES[locale.value][key].replace(/\{(\w+)\}/g, (whole, name: string) =>
    name in params ? String(params[name]) : whole,
  )
}
