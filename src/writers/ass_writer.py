"""ASS/SSA 자막 포맷 출력.

화자별 색상 자동 할당, 화자 이름 매핑, 2인 대화 좌/우 위치 배분을 지원한다.
"""

from __future__ import annotations

from pathlib import Path
from typing import TYPE_CHECKING

import structlog

from src.core.exceptions import WriterError
from src.writers.base import SubtitleWriter

if TYPE_CHECKING:
    from src.models.result import TranscriptionResult
    from src.models.segment import TranscriptionSegment

log = structlog.get_logger(__name__)

# 화자별 색상 팔레트 (ASS BGR 형식: &HBBGGRR)
_SPEAKER_COLORS: list[str] = [
    "&H00FFFFFF",  # 흰색
    "&H0000FFFF",  # 노란색
    "&H0000FF00",  # 초록색
    "&H00FF0000",  # 파란색
    "&H000000FF",  # 빨간색
    "&H00FF00FF",  # 마젠타
    "&H00FFFF00",  # 시안
    "&H000080FF",  # 주황색
]

# 2인 대화 위치 (MarginL, MarginR 기반)
_POSITION_LEFT = {"MarginL": 20, "MarginR": 200}
_POSITION_RIGHT = {"MarginL": 200, "MarginR": 20}
_POSITION_CENTER = {"MarginL": 20, "MarginR": 20}


def _format_ass_time(seconds: float) -> str:
    """초를 ASS 타임스탬프 형식으로 변환한다.

    Returns:
        'H:MM:SS.cc' 형식 문자열 (centiseconds).
    """
    if seconds < 0:
        seconds = 0.0
    hours = int(seconds // 3600)
    minutes = int((seconds % 3600) // 60)
    secs = int(seconds % 60)
    centis = round((seconds % 1) * 100)
    if centis >= 100:
        centis = 0
        secs += 1
        if secs >= 60:
            secs = 0
            minutes += 1
            if minutes >= 60:
                minutes = 0
                hours += 1
    return f"{hours}:{minutes:02d}:{secs:02d}.{centis:02d}"


class ASSWriter(SubtitleWriter):
    """ASS 포맷 자막 출력.

    화자별 색상/위치 스타일을 자동 생성한다.
    """

    @property
    def format_name(self) -> str:
        return "ass"

    @property
    def file_extension(self) -> str:
        return "ass"

    def write(self, result: TranscriptionResult, output_path: str | Path) -> Path:
        """결과를 ASS 파일로 출력한다.

        Args:
            result: TranscriptionResult 인스턴스.
            output_path: 출력 파일 경로.

        Returns:
            저장된 파일의 Path.

        Raises:
            WriterError: 출력 실패 시.
        """
        path = Path(output_path)
        path.parent.mkdir(parents=True, exist_ok=True)

        speakers = _collect_speakers(result.segments)
        style_map = _build_style_map(speakers)

        try:
            content = _build_ass_content(result, style_map)
            path.write_text(content, encoding="utf-8")
            log.info("ASS 파일 저장 완료", path=str(path), segments=len(result.segments))
            return path
        except OSError as e:
            raise WriterError(f"ASS 파일 저장 실패: {path} ({e})") from e


def _collect_speakers(segments: list[TranscriptionSegment]) -> list[str]:
    """세그먼트에서 고유 화자 목록을 추출한다 (등장 순서 유지)."""
    seen: set[str] = set()
    speakers: list[str] = []

    for seg in segments:
        if seg.speaker is None:
            continue
        ids = [seg.speaker] if isinstance(seg.speaker, str) else seg.speaker

        for s in ids:
            if s not in seen:
                seen.add(s)
                speakers.append(s)

    return speakers


def _build_style_map(speakers: list[str]) -> dict[str, dict[str, str | int]]:
    """화자별 스타일 속성을 생성한다.

    Returns:
        ``{speaker_id: {"color": ..., "MarginL": ..., "MarginR": ...}}``
    """
    style_map: dict[str, dict[str, str | int]] = {}
    num_speakers = len(speakers)

    for i, speaker in enumerate(speakers):
        color = _SPEAKER_COLORS[i % len(_SPEAKER_COLORS)]

        # 2인 대화 좌/우 배분
        if num_speakers == 2:
            pos = _POSITION_LEFT if i == 0 else _POSITION_RIGHT
        else:
            pos = _POSITION_CENTER

        style_map[speaker] = {
            "color": color,
            "MarginL": pos["MarginL"],
            "MarginR": pos["MarginR"],
        }

    return style_map


def _build_ass_content(
    result: TranscriptionResult,
    style_map: dict[str, dict[str, str | int]],
) -> str:
    """ASS 파일 전체 내용을 생성한다."""
    lines: list[str] = []

    # Script Info
    lines.append("[Script Info]")
    lines.append(f"Title: {result.metadata.source_file}")
    lines.append("ScriptType: v4.00+")
    lines.append("WrapStyle: 0")
    lines.append("ScaledBorderAndShadow: yes")
    lines.append(f"; Generated by SubWyrhta {result.metadata.subwyrhta_version}")
    lines.append("")

    # V4+ Styles
    lines.append("[V4+ Styles]")
    lines.append(
        "Format: Name, Fontname, Fontsize, PrimaryColour, SecondaryColour, "
        "OutlineColour, BackColour, Bold, Italic, Underline, StrikeOut, "
        "ScaleX, ScaleY, Spacing, Angle, BorderStyle, Outline, Shadow, "
        "Alignment, MarginL, MarginR, MarginV, Encoding"
    )

    # Default style
    lines.append(
        "Style: Default,Arial,20,&H00FFFFFF,&H000000FF,"
        "&H00000000,&H80000000,0,0,0,0,"
        "100,100,0,0,1,2,1,"
        "2,20,20,20,1"
    )

    # Speaker styles
    for speaker, attrs in style_map.items():
        color = attrs["color"]
        margin_l = attrs["MarginL"]
        margin_r = attrs["MarginR"]
        lines.append(
            f"Style: {speaker},Arial,20,{color},&H000000FF,"
            f"&H00000000,&H80000000,0,0,0,0,"
            f"100,100,0,0,1,2,1,"
            f"2,{margin_l},{margin_r},20,1"
        )

    lines.append("")

    # Events
    lines.append("[Events]")
    lines.append("Format: Layer, Start, End, Style, Name, MarginL, MarginR, MarginV, Effect, Text")

    for seg in result.segments:
        start = _format_ass_time(seg.start)
        end = _format_ass_time(seg.end)
        style = _get_style_name(seg, style_map)
        # ASS에서 줄바꿈은 \N
        text = seg.text.replace("\n", "\\N")
        lines.append(f"Dialogue: 0,{start},{end},{style},,0,0,0,,{text}")

    lines.append("")
    return "\n".join(lines)


def _get_style_name(
    seg: TranscriptionSegment,
    style_map: dict[str, dict[str, str | int]],
) -> str:
    """세그먼트에 적용할 스타일 이름을 반환한다."""
    if seg.speaker is None:
        return "Default"

    if isinstance(seg.speaker, str):
        return seg.speaker if seg.speaker in style_map else "Default"

    # 다화자 → 첫 번째 화자 스타일 사용
    if isinstance(seg.speaker, list) and seg.speaker:
        return seg.speaker[0] if seg.speaker[0] in style_map else "Default"

    return "Default"
